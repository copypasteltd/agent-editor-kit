    def test_real_vfr_reverse_nested_sequence_keeps_original_display_intervals(self):
        self.s['duration_tick'] = 225000
        rgba = np.ones((8, 16, 32, 4), np.float32)
        for i in range(8):
            rgba[i, :, :, :3] = (i+1)/10
        self.visual(rgba, vfr=True)
        child = copy.deepcopy(self.s); child['id'] = 'child'; child['name'] = 'native VFR'
        child['tracks'][0]['id'] = 'child_video'; child['tracks'][1]['id'] = 'child_audio'
        child['tracks'][0]['clips'][0]['id'] = 'native_clip'
        self.p['sequences'].append(child)
        self.s['tracks'][0]['clips'] = [{'id': 'container', 'sequence_id': 'child', 'timeline_start_tick': 0,
            'source_in_tick': 0, 'source_out_tick': 225000, 'duration_tick': 225000, 'reverse': True}]
        result = self.execute()
        y = self.decode_y(result['path'], 32, 16)[:, 0, 8, 16]
        from fractions import Fraction
        from bisect import bisect_left
        points = [Fraction(n, 8) for n in [0, 1, 3, 5, 8, 11, 15, 20]]
        expected_indices = [max(0, bisect_left(points, Fraction(5, 2)-Fraction(n, 10))-1) for n in range(25)]
        expected = np.array([64+876*float(rgba[i, 0, 0, 0]) for i in expected_indices])
        self.assertLessEqual(float(np.max(np.abs(y-expected))), 1.5)
        self.assertEqual(result['delivery']['pixel_pipeline']['source_receipts']['picture']['demux_origin'], '5')
        self.assertTrue(result['delivery']['pixel_pipeline']['providers_closed_before_publish'])
        self.assert_clean()

