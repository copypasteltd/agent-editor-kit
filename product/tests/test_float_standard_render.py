    def test_mid_producer_cancel_public_resume_and_changed_setting_rejection(self):
        from ai_ad_editor.float_timeline import FloatTimeline
        self.s['duration_tick'] = 90000
        self.visual(np.broadcast_to(np.array([.4, .4, .4, 1], np.float32), (10, 16, 32, 4)).copy())
        save_project(self.root, self.p)
        marker = self.base/'cancel.flag'; original_frame = FloatTimeline.render_frame
        def cancel_after_first(timeline, index):
            value = original_frame(timeline, index)
            if index == 0:
                marker.write_bytes(b'cancel requested after real source frame')
            return value
        with patch.object(FloatTimeline, 'render_frame', cancel_after_first):
            code, value = self.invoke('render', '--project', self.root, '--output', self.root/'renders/resumed.mkv', '--cancel-file', marker)
        self.assertEqual(code, 8, value)
        operation = value['operation_id']; self.assertTrue(operation, value)
        self.assertFalse((self.root/'renders/resumed.mkv').exists()); self.assert_clean()
        marker.unlink()
        code, value = self.invoke('render', '--project', self.root, '--resume', operation, '--crf', 5)
        self.assertEqual(code, 2, value)
        self.assertEqual(value['errors'][0]['code'], 'RESUME_INPUT_CHANGED')
        code, value = self.invoke('render', '--project', self.root, '--resume', operation)
        self.assertEqual(code, 0, value)
        self.assertEqual(value['data']['resume_of'], operation)
        self.assertEqual(value['data']['delivery']['pixel_pipeline']['transport']['frames'], 10)
        self.assert_clean()


